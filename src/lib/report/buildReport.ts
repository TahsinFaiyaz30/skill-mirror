export const practiceDisclaimer =
  "Practice signal generated by AI for coaching. Not a hiring decision.";
export const hiringDisclaimer =
  "AI recommendation to support, not replace, human judgement.";
function companyView(
  s: SessionRow,
  turns: TurnRow[],
  segments: (typeof transcriptSegments.$inferSelect)[],
  score: number,
  weights: CompanyView["effectiveWeights"],
  recommend: string,
): CompanyView {
  const provenanceCounts = { company: 0, ai_plan: 0, ai_followup: 0 };
  for (const turn of turns)
    if (turn.questionSource !== "system")
      provenanceCounts[turn.questionSource]++;
  return {
    weightedScore: score,
    effectiveWeights: weights,
    recommendation: recommend,
    passThreshold: s.config.evaluation.passThreshold ?? 70,
    nonverbalPolicy: s.config.evaluation.nonverbalPolicy,
    coverage:
      s.config.mode === "auto"
        ? []
        : s.config.customQuestions.map((q) => {
            const saved = s.strategistState?.coverage[q.id];
            const turn = turns.find((turn) => turn.openingQuestionId === q.id);
            const status =
              saved?.status === "asked" ||
              saved?.status === "skipped_by_candidate"
                ? saved.status
                : turn
                  ? "asked"
                  : "unasked";
            return {
              openingQuestionId: q.id,
              text: q.text,
              phase: q.phase,
              mustAsk: q.mustAsk,
              status,
              turnIdx: turn?.idx ?? saved?.turnIdx ?? null,
              total: turn?.scoreTotal ?? null,
              outcome: turn?.scores?.outcome ?? null,
              followUpsAsked: turns.filter(
                (item) => item.strategistOutput?.parentQuestionId === q.id,
              ).length,
            };
          }),
    provenanceCounts,
    transcript: [...segments]
      .sort((a, b) => a.startMs - b.startMs)
      .map((line) => ({
        speaker: line.speaker === "ai" ? "Interviewer" : "Candidate",
        text: line.text,
        startMs: line.startMs,
        endMs: line.endMs,
        turnIdx: line.turnIdx,
        questionSource:
          turns.find((turn) => turn.idx === line.turnIdx)?.questionSource ??
          null,
      })),
    githubProjects: (s.plan?.github_projects ?? []).map(
      ({ name, url, summary }) => ({ name, url, summary }),
    ),
  };
}
export function buildReport(
  session: SessionRow,
  turns: TurnRow[],
  baseline: Baseline,
  timeline: MetricSecond[],
  pitch: PitchFrame[],
  events: SessionEvent[],
  track: WordTrack | null,
  segments: (typeof transcriptSegments.$inferSelect)[],
) {
  const policy = session.config.evaluation.nonverbalPolicy;
  const words = track
    ? new Map(
        [...alignWords(turns, track)].map(([key, value]) => [key, value.words]),
      )
    : new Map();
  const alignedWords = [...words.values()].flat().sort((a, b) => a.s - b.s);
  const delivery = aggregateDelivery(turns, timeline, pitch, words);
  const technical = technicalResults(session, turns);
  const pressure = pressureTurns(turns, technical.competencies);
  const soft = softSkills(policy, turns, delivery, baseline.fields, pressure);
  const components = {
    technical: technical.score,
    behavioral: meanComponent(turns, "behavioral"),
    cv: meanComponent(turns, "cv_deep_dive"),
    soft: soft.score,
  };
  const { score, effectiveWeights } = overallScore(
    components,
    session.config.evaluation.weights,
  );
  const integrity = calculateIntegrity(events);
  const ceilings = technical.competencies
    .filter((c) => !c.notAssessed)
    .map((c) => c.ceiling)
    .filter(present);
  const verdict =
    session.kind === "company"
      ? null
      : practiceVerdict(
          integrity.badge === "review",
          technical.score,
          (mean(ceilings) ?? 0) / technical.expectedLevel,
          soft.score,
          soft.data.maturityScore,
        );
  const recommend =
    session.kind === "practice"
      ? null
      : recommendation(
          integrity.badge === "review",
          score,
          session.config.evaluation.passThreshold ?? 70,
        );
  const avgStress = (items: TurnRow[]) =>
    mean(items.map((turn) => turn.finalMetrics?.stress).filter(present));
  const a = avgStress(pressure),
    b = avgStress(turns.filter((turn) => !pressure.includes(turn)));
  const report: ReportData = {
    version: 1,
    generatedAt: new Date().toISOString(),
    session: {
      kind: session.kind,
      company: session.company,
      roleTitle: session.roleTitle,
      seniority: session.seniority,
      lengthMinutes: session.lengthMinutes,
      durationMs: session.durationMs ?? 0,
      endReason: session.endReason,
      startedAt: session.startedAt?.toISOString() ?? null,
      transcriptSource: track ? "whisper" : "live",
      nonverbalPolicy: policy,
    },
    headline: {
      overallScore: score,
      verdict,
      recommendation: recommend,
      summary: "",
      integrityBadge: integrity.badge,
      disclaimer:
        session.kind === "company" ? hiringDisclaimer : practiceDisclaimer,
    },
    components: { ...components, effectiveWeights },
    technical,
    softSkills: soft.data,
    composure:
      policy === "off"
        ? null
        : {
            pressureDelta: a === null || b === null ? null : a - b,
            commentary: "",
            points: turns
              .filter(
                (turn) =>
                  turn.scores &&
                  (turn.itemKind === "technical" ||
                    turn.phase === "presentation"),
              )
              .map((turn) => ({
                turnIdx: turn.idx,
                label: PHASE_LABELS[turn.phase],
                difficulty: turn.difficulty,
                total: turn.scoreTotal,
                composure: turn.finalMetrics?.composure ?? null,
                outcome: turn.scores?.outcome ?? null,
              })),
          },
    timeline: reportTimeline(
      session,
      turns,
      timeline,
      alignedWords,
      events,
      baseline,
    ),
    keyMoments: [],
    turns: turns.map((turn) => ({
      turnIdx: turn.idx,
      phase: turn.phase,
      kind: turn.itemKind,
      label: PHASE_LABELS[turn.phase],
      questionSource: turn.questionSource,
      question: turn.questionText,
      transcript: turn.answerTranscriptFinal ?? turn.answerTranscriptLive ?? "",
      scores: turn.scores,
      outcome: turn.scores?.outcome ?? null,
      composure: turn.finalMetrics?.composure ?? null,
      voice: policy === "off" ? null : (turn.finalMetrics?.voice ?? null),
      vision: policy === "off" ? null : (turn.finalMetrics?.vision ?? null),
      tone: policy === "off" ? null : turn.tone,
      feedback: "",
      idealOutline: [],
    })),
    stats: statRows(delivery, baseline.fields, policy),
    integrity,
    practicePlan: [],
    summaryLists: { strengths: [], growthAreas: [] },
    eligibility: certificateEligibility(
      session.kind,
      session.endReason,
      integrity.badge,
      technical.competencies,
    ),
    baseline,
    ...(recommend && {
      companyView: companyView(
        session,
        turns,
        segments,
        score,
        effectiveWeights,
        recommend,
      ),
    }),
  };
  return {
    report,
    candidates: keyMomentCandidates(
      turns,
      events,
      alignedWords,
      report.session.durationMs,
      policy === "off",
    ),
  };
}
